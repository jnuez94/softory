"""Put softory's operating instructions where Codex and Claude Code read them,
without changing any file the project tracks in git.

- Codex reads ``AGENTS.override.md`` instead of ``AGENTS.md`` when both exist,
  and has no import syntax, so the instructions are inlined.
- Claude Code reads ``CLAUDE.md`` and ``CLAUDE.local.md``, and reads
  ``AGENTS.md`` only when neither exists. Creating ``CLAUDE.local.md`` turns
  that fallback off, so the block re-imports ``@AGENTS.md`` when the project
  relied on it.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from . import grants
from .errors import SoftoryError
from .gitlocal import is_tracked

START = "<!-- softory:start -->"
END = "<!-- softory:end -->"
OVERRIDE_HEADER = (
    "<!-- Generated by softory: a copy of the tracked AGENTS.md plus softory's block.\n"
    "     Codex reads this file instead of AGENTS.md. Regenerate after AGENTS.md\n"
    "     changes with: .agents/softory/bin/softory sync -->\n\n"
)


def compose(base: str, stand_ins: list[dict[str, Any]]) -> str:
    """The instruction body: softory's block plus this project's active stand-ins."""
    active = [grant for grant in stand_ins if grants.is_active(grant)]
    if not active:
        return base
    lines = ["", "### Stand-ins on this project", "",
             "These agents act for a softory role. They review and close wherever that role may, within its "
             "boundaries, and only on the tasks and dates shown. A role-wide stand-in never reviews the "
             "specialist's own work; the backup reviewer in gates.json does.", ""]
    lines += [f"- {grants.describe(grant)}" for grant in active]
    return base.rstrip("\n") + "\n" + "\n".join(lines) + "\n"


def managed_block(body: str) -> str:
    return f"{START}\n{body.strip()}\n{END}\n"


def upsert_block(text: str, block: str) -> str:
    """Replace softory's managed block in ``text``, or append it."""
    if START in text and END in text:
        head, _, rest = text.partition(START)
        _, _, tail = rest.partition(END)
        return head + block.rstrip("\n") + tail
    separator = "" if not text.strip() else ("\n" if text.endswith("\n") else "\n\n")
    return text + separator + block


def remove_block(text: str) -> str:
    if START not in text or END not in text:
        return text
    head, _, rest = text.partition(START)
    _, _, tail = rest.partition(END)
    return (head.rstrip("\n") + "\n" + tail.lstrip("\n")).lstrip("\n") if head.strip() or tail.strip() else ""


def plan(root: Path, created_before: set[str]) -> dict[str, str]:
    """Decide which file gets which treatment.

    Returns a map of relative path to one of ``create`` (new file softory owns),
    ``block`` (insert a managed block into an untracked file), or ``override``
    (generate AGENTS.override.md from a tracked AGENTS.md).
    """
    actions: dict[str, str] = {}
    for name in ("AGENTS.override.md", "CLAUDE.local.md"):
        if (root / name).exists() and is_tracked(root, name):
            raise SoftoryError(
                f"{name} is tracked in git; softory cannot add hidden instructions to it.",
                "tracked_instruction_file",
            )
    agents = root / "AGENTS.md"
    if not agents.exists() or "AGENTS.md" in created_before:
        actions["AGENTS.md"] = "create"
    elif is_tracked(root, "AGENTS.md"):
        override = root / "AGENTS.override.md"
        user_owned = override.exists() and "AGENTS.override.md" not in created_before
        actions["AGENTS.override.md"] = "block" if user_owned else "override"
    else:
        actions["AGENTS.md"] = "block"
    local = root / "CLAUDE.local.md"
    user_local = local.exists() and "CLAUDE.local.md" not in created_before
    actions["CLAUDE.local.md"] = "block" if user_local else "create"
    return actions


def claude_body(root: Path, agents_action: str | None, instructions: str) -> str:
    """CLAUDE.local.md's block: the instructions, plus @AGENTS.md if the project used it."""
    has_claude_md = (root / "CLAUDE.md").exists() or (root / ".claude" / "CLAUDE.md").exists()
    project_agents = (root / "AGENTS.md").exists() and agents_action != "create"
    lines = []
    if project_agents and not has_claude_md:
        lines += ["Project instructions (CLAUDE.local.md disables Claude Code's AGENTS.md fallback, so import it):", "", "@AGENTS.md", ""]
    return "\n".join(lines) + instructions


def write(root: Path, actions: dict[str, str], instructions: str) -> list[str]:
    """Apply ``actions``. Returns the files softory now owns outright."""
    owned: list[str] = []
    block = managed_block(instructions)
    for name, action in actions.items():
        path = root / name
        body = block
        if name == "CLAUDE.local.md":
            body = managed_block(claude_body(root, actions.get("AGENTS.md"), instructions))
        if action == "create":
            title = "# Agent instructions\n\n" if name == "AGENTS.md" else "# Local Claude Code instructions\n\n"
            path.write_text(title + body, encoding="utf-8")
            owned.append(name)
        elif action == "override":
            source = (root / "AGENTS.md").read_text(encoding="utf-8")
            path.write_text(OVERRIDE_HEADER + upsert_block(source, block), encoding="utf-8")
            owned.append(name)
        else:
            path.write_text(upsert_block(path.read_text(encoding="utf-8"), body), encoding="utf-8")
    return owned
